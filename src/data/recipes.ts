import type { Difficulty, IngredientRole, RecipeIngredient, Unit } from '../types';

/** Raw recipe source. Allergens, dietary tags and components are derived from the ingredient data. */
export interface RecipeSource {
  id: string;
  name: string;
  description: string;
  emoji: string;
  cuisine: string;
  mainProtein: string;
  proteinGroup: string;
  prepMinutes: number;
  cookMinutes: number;
  difficulty: Difficulty;
  servings: number;
  ingredients: RecipeIngredient[];
  steps: string[];
}

type Row = [foodId: string, amount: number, unit: Unit, role: 'p' | 'v' | 'c' | 'o', note?: string];
const ROLE: Record<Row[3], IngredientRole> = { p: 'protein', v: 'veg', c: 'carb', o: 'other' };

function R(
  id: string,
  name: string,
  meta: {
    d: string;
    e: string;
    cuisine: string;
    protein: string;
    group: string;
    prep: number;
    cook: number;
    diff?: Difficulty;
    serves?: number;
  },
  rows: Row[],
  steps: string[],
): RecipeSource {
  return {
    id,
    name,
    description: meta.d,
    emoji: meta.e,
    cuisine: meta.cuisine,
    mainProtein: meta.protein,
    proteinGroup: meta.group,
    prepMinutes: meta.prep,
    cookMinutes: meta.cook,
    difficulty: meta.diff ?? 'Easy',
    servings: meta.serves ?? 4,
    ingredients: rows.map(([foodId, amount, unit, role, note]) => ({ foodId, amount, unit, role: ROLE[role], ...(note ? { note } : {}) })),
    steps,
  };
}

